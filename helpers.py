def get_tiktok_title(url):
    try:
        headers = {
            "User-Agent": (
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                "AppleWebKit/537.36 (KHTML, like Gecko) "
                "Chrome/120.0.0.0 Safari/537.36"
            ),
            "Accept-Language": "en-US,en;q=0.9",
            "Referer": "https://www.google.com/",
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9",
        }

        response = requests.get(url, headers=headers, timeout=5)
        html = response.text

        # Try SIGI_STATE block
        match = re.search(
            r'<script[^>]*id="SIGI_STATE"[^>]*>(.*?)</script>',
            html,
            flags=re.DOTALL
        )

        if match:
            json_text = match.group(1)
            desc_match = re.search(r'"desc"\s*:\s*"([^"]+)"', json_text)
            if desc_match:
                return desc_match.group(1).strip()

        # Fallback: search entire HTML
        desc_match = re.search(r'"desc"\s*:\s*"([^"]+)"', html)
        if desc_match:
            return desc_match.group(1).strip()

        return None

    except Exception:
        return None



def get_instagram_title(url):
    try:
        headers = {"User-Agent": "Mozilla/5.0"}
        response = requests.get(url, headers=headers, timeout=5)
        soup = BeautifulSoup(response.text, "html.parser")

        meta = soup.find("meta", {"property": "og:description"})
        if not meta or not meta.get("content"):
            return None

        raw = meta["content"]

        # Extract full caption inside quotes (multi-line safe)
        match = re.search(r'"(.+)"', raw, flags=re.DOTALL)
        if match:
            caption = match.group(1).strip()
            return caption

        return raw

    except Exception:
        return None


def shorten_title(title, words=10):
    if not title:
        return "Untitled"
    return " ".join(title.split()[:words])


def extract_urls(text):
    pattern = r'(https?://[^\s]+)'
    return re.findall(pattern, text)




